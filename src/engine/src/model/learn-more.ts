/** A realm's link: its own page, else its capital's, since a city-state is its city (Gubla's is Byblos'). */
export function realmLink(p: FixedPower): LearnMore | undefined {
  const own = RealmLinks.get(p);
  if (own !== undefined) return own;
  const capital = WorldMap.default.provinces.find((x) => x.home === p && x.capital);
  return capital !== undefined ? PlaceLinks.get(capital.id) : undefined;
}
