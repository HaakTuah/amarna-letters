/**
 * "Learn more, and what is invented" (Interface, build order item 17+++b): each real place, realm, person and language
 * in the game's data and its "Learn more" link, mostly its English Wikipedia page, opened outside the game. `title` is the
 * page's own title as the card shows it; `note` is a line for where the game takes a side the page does not (a disputed
 * name or site). Where a real person or place has no page of its own, the link goes to the page that tells of them, and
 * `title` says which. Presentation only: never in a request to a model. Each link is checked weekly (`scripts/links.mjs`).
 */
import type { FixedPower } from "./power.ts";

export interface LearnMore {
  readonly url: string;
  readonly title: string;
  readonly note?: string;
}

const w = (title: string, note?: string): LearnMore => ({
  url: `https://en.wikipedia.org/wiki/${encodeURIComponent(title.replace(/ /g, "_")).replace(/%2C/g, ",").replace(/%28/g, "(").replace(/%29/g, ")")}`,
  title,
  ...(note !== undefined ? { note } : {}),
});

